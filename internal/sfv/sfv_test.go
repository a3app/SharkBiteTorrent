package sfv

import (
	"context"
	"fmt"
	"hash/crc32"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestParse(t *testing.T) {
	in := "; Generated by some tool\r\n" +
		"release.r00 1A2B3C4D\r\n" +
		"My Movie (2026).mkv\tdeadbeef\n" +
		"sub\\file.nfo 00000001\n" +
		"broken line\n" +
		"short.bin ABC\n"
	es, err := Parse(strings.NewReader(in))
	if err != nil {
		t.Fatal(err)
	}
	want := []Entry{{"release.r00", 0x1A2B3C4D}, {"My Movie (2026).mkv", 0xDEADBEEF}, {"sub/file.nfo", 1}}
	if fmt.Sprint(es) != fmt.Sprint(want) {
		t.Fatalf("got %v", es)
	}
}

func TestCheck(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) string {
		p := filepath.Join(dir, filepath.FromSlash(name))
		os.MkdirAll(filepath.Dir(p), 0o755)
		os.WriteFile(p, []byte(body), 0o644)
		return p
	}
	good := crc32.ChecksumIEEE([]byte("good data"))
	files := map[string]string{
		"Release/a.bin": write("Release/a.bin", "good data"),
		"Release/B.BIN": write("Release/B.BIN", "corrupted!"),
		"Release/rel.sfv": write("Release/rel.sfv", fmt.Sprintf(
			"; test\na.bin %08X\nb.bin %08X\nc.bin %08X\n", good, good, good)),
	}
	res, err := Check(context.Background(), files)
	if err != nil {
		t.Fatal(err)
	}
	// a matches; B.BIN is found case-insensitively but corrupted; c is missing.
	if res.Checked != 1 || fmt.Sprint(res.Bad) != "[Release/b.bin]" || fmt.Sprint(res.Missing) != "[Release/c.bin]" {
		t.Fatalf("got %+v", res)
	}
}
